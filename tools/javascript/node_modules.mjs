import { rm, symlink } from "node:fs/promises";
import { join } from "node:path";

async function main() {
  const workspaceRoot = process.env.BUILD_WORKSPACE_DIRECTORY;

  if (!workspaceRoot) {
    throw new Error("BUILD_WORKSPACE_DIRECTORY is not set");
  }

  const nodeModulesPath = join(workspaceRoot, "node_modules");

  await rm(nodeModulesPath, { force: true });
  await symlink("bazel-bin/node_modules", nodeModulesPath, "dir");
}

await main();
